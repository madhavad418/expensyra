// Database access for Expensyra.
//
// The app is written against node:sqlite's synchronous API
// (db.prepare(sql).get/all/run, db.exec). openDatabase() returns either that
// real SQLite database (local use: DATABASE_PATH) or, when DATABASE_URL is a
// postgres:// URL (Railway), an object with the same synchronous API backed
// by Postgres. The Postgres connection lives in a worker thread; each call
// blocks on a shared flag until the worker answers, exactly like a local
// SQLite call blocks. SQL is written in SQLite dialect and translated here.
import { DatabaseSync } from 'node:sqlite';
import { Worker, MessageChannel, receiveMessageOnPort } from 'node:worker_threads';

export function openDatabase({ path, url }) {
  if (url && /^postgres(ql)?:\/\//i.test(url)) return new PgSyncDatabase(url);
  const db = new DatabaseSync(path);
  db.exec('PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON; PRAGMA busy_timeout=5000;');
  db.dialect = 'sqlite';
  return db;
}

// ---- SQLite -> Postgres translation -------------------------------------

// Drop `-- ...` comments outside string literals. Schema comments contain
// apostrophes ("Pleo's") and semicolons that would otherwise confuse the
// literal detection and statement splitting below.
function stripComments(sql) {
  let out = '', inQuote = false;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (ch === "'") inQuote = !inQuote;
    if (!inQuote && ch === '-' && sql[i + 1] === '-') { while (i < sql.length && sql[i] !== '\n') i++; out += '\n'; continue; }
    out += ch;
  }
  return out;
}

// Split into code / string-literal segments so rewrites never touch quoted
// text ('' escapes produce an empty literal segment, which keeps parity).
function mapCode(sql, fn) {
  return sql.split("'").map((seg, i) => (i % 2 ? seg : fn(seg))).join("'");
}

export function translateSql(input) {
  const sql = stripComments(input), s = sql.trim();
  const tableInfo = s.match(/^PRAGMA\s+table_info\(\s*"?(\w+)"?\s*\)/i);
  if (tableInfo) return { sql: `SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '${tableInfo[1]}' ORDER BY ordinal_position`, params: 0 };
  if (/^PRAGMA\b/i.test(s)) return { sql: null };
  const ddl = /^\s*(CREATE|ALTER)\s+TABLE/im.test(sql);
  let n = 0;
  const out = mapCode(sql, code => {
    let c = code
      .replace(/\?(\d+)/g, '$$$1')
      .replace(/\?/g, () => `$${++n}`)
      .replace(/(?<![\w.])date\(/gi, 'sqlite_date(')
      .replace(/(?<![\w.])julianday\(/gi, 'sqlite_julianday(')
      .replace(/(?<![\w.])strftime\(/gi, 'sqlite_strftime(')
      .replace(/\bMAX\(\s*0\s*,/g, 'GREATEST(0,')
      .replace(/\bNOT\s+LIKE\b/g, 'NOT ILIKE')
      .replace(/(?<!NOT )\bLIKE\b/g, 'ILIKE')
      .replace(/\bBEGIN\s+(IMMEDIATE|EXCLUSIVE|DEFERRED)\b/gi, 'BEGIN')
      .replace(/\s+COLLATE\s+NOCASE\b/gi, '');
    if (ddl) c = c
      .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      .replace(/(\w+\s+)REAL\b/g, '$1DOUBLE PRECISION');
    return c;
  });
  return { sql: resolveNullTests(out), params: n };
}

// Postgres fixes a parameter's type at its FIRST appearance, so SQLite-style
// "(? IS NULL OR col = ?)" fails with "could not determine data type".
// If the parameter is also used elsewhere, its IS [NOT] NULL tests are
// decided in JS at run time (the value is known) and inlined as TRUE/FALSE,
// leaving only the typed uses. If it is ONLY null-tested, it is cast to text.
const NULL_MARK = '\u0000';
function resolveNullTests(sql) {
  const uses = new Map();
  mapCode(sql, code => {
    for (const m of code.matchAll(/\$(\d+)(\s+IS\s+(NOT\s+)?NULL\b)?/gi)) {
      const u = uses.get(m[1]) || { total: 0, nullTests: 0 };
      u.total++; if (m[2]) u.nullTests++; uses.set(m[1], u);
    }
    return code;
  });
  return mapCode(sql, code => code.replace(/\$(\d+)\s+IS\s+(NOT\s+)?NULL\b/gi, (all, idx, not) => {
    const u = uses.get(idx);
    if (u.nullTests === u.total) return `$${idx}::text IS ${not ? 'NOT ' : ''}NULL`;
    return `${NULL_MARK}${idx}:${not ? 1 : 0}${NULL_MARK}`;
  }));
}
function bindNullTests(sql, values) {
  if (!sql.includes(NULL_MARK)) return sql;
  return sql.replace(/\u0000(\d+):([01])\u0000/g, (all, idx, not) => {
    const isNull = values[Number(idx) - 1] == null;
    return (not === '1' ? !isNull : isNull) ? 'TRUE' : 'FALSE';
  });
}

// Multi-statement db.exec(): drop PRAGMAs, translate the rest.
function translateExec(sql) {
  return stripComments(sql).split(/;\s*(?=(?:[^']*'[^']*')*[^']*$)/)
    .map(part => part.trim()).filter(Boolean)
    .map(part => translateSql(part).sql).filter(Boolean)
    .join(';\n');
}

// ---- Synchronous Postgres bridge ----------------------------------------

const WAIT_SLICE_MS = 5000;
const MAX_WAIT_MS = Number(process.env.DB_QUERY_TIMEOUT_MS || 15 * 60_000);

class PgSyncDatabase {
  constructor(url) {
    this.dialect = 'postgres';
    this.flag = new Int32Array(new SharedArrayBuffer(4));
    const { port1, port2 } = new MessageChannel();
    this.port = port1;
    const ssl = /^(1|true|yes|require)$/i.test(process.env.DATABASE_SSL || '');
    this.worker = new Worker(new URL('./db-pg-worker.mjs', import.meta.url), {
      workerData: { url, port: port2, flag: this.flag.buffer, ssl },
      transferList: [port2],
    });
    this.worker.unref();
    this.cache = new Map();
    this.idTables = null;
    this.call({ op: 'init' });
    this.refreshIdTables();
  }

  call(msg) {
    Atomics.store(this.flag, 0, 0);
    this.port.postMessage(msg);
    const started = Date.now();
    while (Atomics.wait(this.flag, 0, 0, WAIT_SLICE_MS) === 'timed-out') {
      if (Date.now() - started > MAX_WAIT_MS) throw new Error(`Database call timed out after ${MAX_WAIT_MS} ms`);
    }
    const reply = receiveMessageOnPort(this.port)?.message;
    if (!reply) throw new Error('Database worker returned no reply');
    if (reply.error) {
      const e = new Error(reply.error.message);
      e.code = reply.error.code; e.detail = reply.error.detail;
      // Keep the SQLite-style wording the app already matches on.
      if (e.code === '23505') e.message = `UNIQUE constraint failed: ${e.message}`;
      if (e.code === '23503') e.message = `FOREIGN KEY constraint failed: ${e.message}`;
      if (e.code === '23514') e.message = `CHECK constraint failed: ${e.message}`;
      throw e;
    }
    return reply.result;
  }

  // Tables with an integer id column: INSERTs into them return it, which is
  // what node:sqlite exposes as lastInsertRowid.
  refreshIdTables() {
    const rows = this.call({ op: 'query', mode: 'all', params: [], sql: "SELECT table_name FROM information_schema.columns WHERE table_schema = current_schema() AND column_name = 'id'" });
    this.idTables = new Set(rows.map(r => r.table_name));
    this.cache.clear();
  }

  exec(sql) {
    const translated = translateExec(sql);
    if (!translated) return;
    this.call({ op: 'exec', sql: translated });
    if (/\b(CREATE|ALTER|DROP)\s+TABLE\b/i.test(translated)) this.refreshIdTables();
  }

  prepare(sql) {
    let t = this.cache.get(sql);
    if (!t) {
      t = translateSql(sql);
      const insert = t.sql && t.sql.match(/^\s*INSERT\s+INTO\s+"?(\w+)"?/i);
      t.returningId = Boolean(insert && this.idTables.has(insert[1]) && !/\bRETURNING\b/i.test(t.sql));
      this.cache.set(sql, t);
    }
    const db = this;
    const params = args => args.map(v => (typeof v === 'boolean' ? (v ? 1 : 0) : v === undefined ? null : v));
    const run = (mode, args) => {
      if (!t.sql) return mode === 'all' ? [] : mode === 'run' ? { changes: 0, lastInsertRowid: null } : undefined;
      const values = params(args);
      const base = bindNullTests(t.sql, values);
      const sqlText = mode === 'run' && t.returningId ? `${base} RETURNING id` : base;
      const result = db.call({ op: 'query', mode, sql: sqlText, params: values });
      if (mode === 'run' && /^\s*(ALTER|CREATE|DROP)\s+TABLE/i.test(sqlText)) db.refreshIdTables();
      return result;
    };
    return {
      get: (...args) => run('get', args),
      all: (...args) => run('all', args),
      run: (...args) => run('run', args),
    };
  }

  close() {
    try { this.call({ op: 'close' }); } finally { this.worker.terminate(); }
  }
}
